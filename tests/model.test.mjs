import assert from 'node:assert/strict';
import {Hospital,STORAGE_KEY,money} from '../docs/model.mjs';
const memory=()=>{const data=new Map();return {getItem:k=>data.get(k)??null,setItem:(k,v)=>data.set(k,v)};};
let count=0;const check=(name,fn)=>{fn();count++;console.log('PASS '+name);};
const storage=memory();const h=new Hospital(storage);
check('starts empty',()=>assert.equal(h.data.patients.length,0));
check('rejects blank name',()=>assert.throws(()=>h.register(' ',25,'9000000000')));
check('rejects invalid age',()=>assert.throws(()=>h.register('Demo',0,'9000000000')));
check('rejects decimal age',()=>assert.throws(()=>h.register('Demo','25.5','9000000000')));
check('rejects invalid contact',()=>assert.throws(()=>h.register('Demo',25,'bad')));
check('generates patient ID',()=>assert.equal(h.register('Arun Demo',25,'9000000000').id,1));
h.register('Riya Demo',30,'9000000001');
check('rejects unknown patient',()=>assert.throws(()=>h.book(999,'Mehta','2026-10-20','10:30')));
check('rejects invalid calendar date',()=>assert.throws(()=>h.book(1,'Mehta','2026-02-30','10:30')));
check('rejects invalid time',()=>assert.throws(()=>h.book(1,'Mehta','2026-10-20','25:30')));
check('books valid appointment',()=>assert.equal(h.book(1,'Mehta','2026-10-20','10:30').id,1));
check('rejects doctor clash ignoring case',()=>assert.throws(()=>h.book(2,'mehta','2026-10-20','10:30')));
check('rejects patient clash',()=>assert.throws(()=>h.book(1,'Sharma','2026-10-20','10:30')));
check('rejects blank note',()=>assert.throws(()=>h.addNote(1,'')));
check('saves medical note',()=>assert.equal(h.addNote(1,'Fictional note').patientId,1));
for(const value of ['NaN','Infinity','-50','0','1.001','1e5'])check('rejects amount '+value,()=>assert.throws(()=>h.bill(1,'Consultation',value)));
check('preserves exact decimal cents',()=>assert.equal(h.bill(1,'Consultation','500.10').cents,50010));
check('formats Indian currency',()=>assert.match(money(50010),/500\.10/));
check('marks existing bill paid',()=>{h.markPaid(1);assert.equal(h.data.bills[0].paid,true);});
check('rejects unknown bill',()=>assert.throws(()=>h.markPaid(999)));
check('reloads all data from storage',()=>assert.deepEqual(new Hospital(storage).data,h.data));
check('failed save leaves current memory unchanged',()=>{const s=memory();const broken=new Hospital(s);s.setItem=()=>{throw Error('Quota exceeded');};assert.throws(()=>broken.register('Demo',25,'9000000000'));assert.equal(broken.data.patients.length,0);});
check('loads a complete fictional dataset',()=>{const demo=new Hospital(memory());demo.sample();assert.equal(demo.data.patients.length,2);assert.equal(demo.data.bills.length,1);});
check('sample does not overwrite existing records',()=>assert.throws(()=>h.sample()));
check('reset persists empty state',()=>{h.clear();assert.equal(new Hospital(storage).data.patients.length,0);});
check('invalid saved schema rejected',()=>{const s=memory();s.setItem(STORAGE_KEY,'{}');assert.throws(()=>new Hospital(s));});
console.log(`TOTAL: ${count} browser-model checks passed.`);
